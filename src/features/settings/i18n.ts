export type TextKey = keyof typeof messages;
export type Locale = 'zh-CN' | 'zh-TW' | 'en' | 'ja' | 'de' | 'fr';
function subscribe(callback: () => void) {
  window.addEventListener('languagechange', callback);
  return () => window.removeEventListener('languagechange', callback);
}
export function resolveLocale(language: string, system: string): Locale {
  const value = language === 'system' ? system : language;
  if (/^zh-(TW|HK|Hant)/iu.test(value)) return 'zh-TW';
  if (value.startsWith('zh')) return 'zh-CN';
  for (const code of ['en', 'ja', 'de', 'fr'] as const) if (value.startsWith(code)) return code;
  return 'en';
}
export function translate(key: TextKey, locale: Locale): string {
  const index = { 'zh-TW': 0, en: 1, ja: 2, de: 3, fr: 4 } as const;
  return locale === 'zh-CN' ? key : messages[key][index[locale]];
}
export function useText() {
  const language = useSettingsUi((state) => state.language);
  const system = useSyncExternalStore(
    subscribe,
    () => navigator.language,
    () => 'zh-CN',
  );
  const locale = resolveLocale(language, system);
  return { locale, t: (key: TextKey) => translate(key, locale) };
}
